def main():
    # Red causal sin fotos: los nodos se dibujan con icono + nombre (medalla de color).
    for _n in NODOS:
        _n[11] = ''
        _n[14] = ''
        _n[15] = ''
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = 'LEEME'
    ws['A1'] = 'RED CAUSAL DE PROBLEMAS DE KENNEDY (3 NIVELES)'
    ws['A2'] = 'N1 manifestaciones -> N2 efectos -> N3 causa raiz + 10 indicadores. Fuente: guion de 4 minutos del grupo.'

    def sheet(name, header, data_rows):
        w = wb.create_sheet(name)
        for c, h in enumerate(header, 1):
            w.cell(1, c).value = h
        for r, row in enumerate(data_rows, 2):
            for c, v in enumerate(row, 1):
                w.cell(r, c).value = v
        return w

    sheet('CAPAS', ['Codigo', 'Capa', 'Descripcion en el panel', 'Color (HEX)', 'Icono (Font Awesome)', 'Insignia'], CAPAS)
    sheet('INTERACCIONES', ['Codigo', 'Tipo de relacion', 'Definicion', 'Color (HEX)', 'Icono (Font Awesome)'], TIPOS)
    sheet('NODOS', ['ID', 'Nombre (name)', 'Capa (cat)', 'Categoria POT (sciname)', 'Escala SETs',
                    'Ubicacion (loc)', 'Proceso que orienta el POT (role)', 'Transformacion o tension (alert)',
                    'Actores que moviliza', 'Hipotesis relacional', 'Fuente normativa', 'Imagen (img, opcional)',
                    'Latitud', 'Longitud', 'Imagen 1', 'Imagen 2', 'Sugerencia de imagenes', 'Icono (Font Awesome)'], NODOS)
    sheet('ARISTAS', ['ID', 'Origen (ID nodo)', 'Destino (ID nodo)', 'Tipo de relacion', 'Detalle del tipo',
                      'Justificacion causal (rationale)', 'Tension', 'Peso', 'Relacion declarada POT',
                      'Relacion operativa real', 'Hipotesis', 'Evidencia'], EDGES)
    sheet('RED', ['Clave', 'Valor'], RED)

    # CONTROL pre-llenado con la validacion (verificada abajo antes de guardar)
    capa_names = {c[1] for c in CAPAS}
    tipo_names = {t[1] for t in TIPOS}
    ids = [n[0] for n in NODOS]
    idset = set(ids)
    from collections import Counter
    deg = Counter()
    for e in EDGES:
        deg[e[1]] += 1
        deg[e[2]] += 1
    checks = [
        len(ids) - len(idset),
        sum(1 for n in NODOS if n[2] not in capa_names),
        sum(1 for e in EDGES if e[1] not in idset),
        sum(1 for e in EDGES if e[2] not in idset),
        sum(1 for e in EDGES if e[3] not in tipo_names),
        sum(1 for e in EDGES if e[1] == e[2]),
        sum(1 for i in ids if deg[i] == 0),
    ]
    wc = sheet('CONTROL', ['Prueba', 'Resultado', 'Estado'], [])
    for i, name in enumerate(CONTROL_ROWS, 2):
        wc.cell(i, 1).value = name
        wc.cell(i, 2).value = checks[i - 2]
        wc.cell(i, 3).value = 'OK' if checks[i - 2] == 0 else 'REVISAR'
    r = len(CONTROL_ROWS) + 2
    wc.cell(r, 1).value = 'ESTADO GLOBAL'
    wc.cell(r, 2).value = 'OK' if all(c == 0 for c in checks) else 'CON ERRORES'
    wc.cell(r, 3).value = str(date.today())
    wc.cell(r + 1, 1).value = 'Total nodos'
    wc.cell(r + 1, 2).value = len(NODOS)
    wc.cell(r + 2, 1).value = 'Total aristas'
    wc.cell(r + 2, 2).value = len(EDGES)

    wb.save(XLSX)
    print('OK:', len(NODOS), 'nodos,', len(EDGES), 'aristas,', len(CAPAS), 'capas,', len(TIPOS),
          'tipos ->', XLSX, '| CONTROL:', wc.cell(r, 2).value)


if __name__ == '__main__':
    main()
